CREATE TABLE IF NOT EXISTS PROGRAM_BENEFIT_HISTORY (
    HISTORY_ID BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    APPLICATION_NO VARCHAR(8) NOT NULL,
    APPLICANT_AADHAR_NUMBER VARCHAR(12) NOT NULL,
    PROGRAM_CODE VARCHAR(10) NOT NULL,
    PERSON_ID BIGINT NULL,
    STATUS VARCHAR(30) NOT NULL,
    START_DATE DATE NULL,
    END_DATE DATE NULL,
    CREATED_DATE DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    KEY IDX_PROGRAM_HISTORY_LOOKUP (APPLICATION_NO, PROGRAM_CODE, STATUS),
    KEY IDX_PROGRAM_HISTORY_CITIZEN (APPLICANT_AADHAR_NUMBER, PROGRAM_CODE, STATUS)
);
