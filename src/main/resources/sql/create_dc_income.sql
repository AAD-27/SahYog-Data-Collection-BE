CREATE TABLE IF NOT EXISTS DC_INCOME (
    INCOME_ID BIGINT NOT NULL AUTO_INCREMENT,
    APPLICATION_NO VARCHAR(8) NOT NULL,
    INCOME_TYPE VARCHAR(100) NOT NULL,
    EMPLOYER_NAME VARCHAR(255) DEFAULT NULL,
    INCOME_START_DATE DATE NOT NULL,
    INCOME_END_DATE DATE DEFAULT NULL,
    PAY_FREQUENCY VARCHAR(50) NOT NULL,
    INCOME_AMOUNT DECIMAL(15,2) NOT NULL,
    APPROX_YEARLY_INCOME DECIMAL(15,2) NOT NULL,
    EMPLOYER_ADDRESS_LINE1 VARCHAR(255) NOT NULL,
    EMPLOYER_ADDRESS_LINE2 VARCHAR(255) DEFAULT NULL,
    EMPLOYER_CITY VARCHAR(100) NOT NULL,
    EMPLOYER_STATE VARCHAR(100) NOT NULL,
    EMPLOYER_COUNTRY VARCHAR(100) NOT NULL,
    EMPLOYER_PINCODE VARCHAR(6) NOT NULL,
    INCOME_VERIFICATION VARCHAR(100) DEFAULT NULL,
    EMPLOYMENT_CATEGORY VARCHAR(100) DEFAULT NULL,
    OCCUPATION_DESIGNATION VARCHAR(150) DEFAULT NULL,
    INCOME_BASIS VARCHAR(100) DEFAULT NULL,
    PAYMENT_MODE VARCHAR(100) DEFAULT NULL,
    VERIFICATION_REFERENCE_NUMBER VARCHAR(150) DEFAULT NULL,
    VERIFICATION_DOCUMENT_DATE DATE DEFAULT NULL,
    CREATED_DATE DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UPDATED_DATE DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (INCOME_ID),
    KEY IDX_DC_INCOME_APPLICATION_NO (APPLICATION_NO),
    CONSTRAINT FK_DC_INCOME_APPLICATION FOREIGN KEY (APPLICATION_NO)
        REFERENCES DC_APPLICATION (APPLICATION_NO) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
