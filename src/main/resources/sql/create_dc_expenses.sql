CREATE TABLE IF NOT EXISTS DC_EXPENSES (
    EXPENSE_ID BIGINT NOT NULL AUTO_INCREMENT,
    APPLICATION_NO VARCHAR(8) NOT NULL,
    EXPENSE_TYPE VARCHAR(100) NOT NULL,
    EXPENSE_DETAIL VARCHAR(255) NOT NULL,
    EXPENSE_FREQUENCY VARCHAR(50) NOT NULL,
    EXPENSE_AMOUNT DECIMAL(15,2) NOT NULL,
    EXPENSE_START_DATE DATE NOT NULL,
    EXPENSE_END_DATE DATE DEFAULT NULL,
    EXPENSE_VERIFICATION VARCHAR(100) DEFAULT NULL,
    SERVICE_PROVIDER_NAME VARCHAR(150) DEFAULT NULL,
    EXPENSE_REFERENCE_NUMBER VARCHAR(150) DEFAULT NULL,
    PAID_BY VARCHAR(100) DEFAULT NULL,
    PAYMENT_MODE VARCHAR(100) DEFAULT NULL,
    BILLING_PERIOD_FROM DATE DEFAULT NULL,
    BILLING_PERIOD_TO DATE DEFAULT NULL,
    CREATED_DATE DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UPDATED_DATE DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (EXPENSE_ID),
    KEY IDX_DC_EXPENSES_APPLICATION_NO (APPLICATION_NO),
    CONSTRAINT FK_DC_EXPENSES_APPLICATION FOREIGN KEY (APPLICATION_NO)
        REFERENCES DC_APPLICATION (APPLICATION_NO) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
