CREATE TABLE IF NOT EXISTS DC_RESOURCES (
    RESOURCE_ID BIGINT NOT NULL AUTO_INCREMENT,
    APPLICATION_NO VARCHAR(8) NOT NULL,
    RESOURCE_TYPE VARCHAR(100) NOT NULL,
    RESOURCE_DETAIL VARCHAR(500) NOT NULL,
    RESOURCE_VALUE DECIMAL(15,2) NOT NULL,
    RESOURCE_START_DATE DATE NOT NULL,
    RESOURCE_END_DATE DATE DEFAULT NULL,
    RESOURCE_VERIFICATION VARCHAR(150) DEFAULT NULL,
    OWNERSHIP_TYPE VARCHAR(100) DEFAULT NULL,
    OWNERSHIP_SHARE_PERCENT DECIMAL(5,2) DEFAULT NULL,
    ASSET_IDENTIFIER VARCHAR(150) DEFAULT NULL,
    ACQUISITION_DATE DATE DEFAULT NULL,
    ENCUMBRANCE_STATUS VARCHAR(100) DEFAULT NULL,
    OUTSTANDING_LIABILITY_AMOUNT DECIMAL(15,2) DEFAULT NULL,
    CREATED_DATE DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UPDATED_DATE DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (RESOURCE_ID),
    KEY IDX_DC_RESOURCES_APPLICATION_NO (APPLICATION_NO),
    CONSTRAINT FK_DC_RESOURCES_APPLICATION FOREIGN KEY (APPLICATION_NO)
        REFERENCES DC_APPLICATION (APPLICATION_NO) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
