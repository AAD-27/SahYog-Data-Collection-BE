CREATE TABLE IF NOT EXISTS DC_USER_ACCOUNT (
    USER_ID BIGINT NOT NULL AUTO_INCREMENT,
    PROFILE_TYPE VARCHAR(30) NOT NULL,
    EMPLOYEE_ID VARCHAR(50) NULL,
    CITIZEN_ID VARCHAR(20) NULL,
    FIRST_NAME VARCHAR(100) NOT NULL,
    MIDDLE_NAME VARCHAR(100) NULL,
    LAST_NAME VARCHAR(100) NOT NULL,
    MOBILE_NUMBER VARCHAR(10) NULL,
    EMAIL VARCHAR(255) NULL,
    DEPARTMENT VARCHAR(150) NULL,
    DESIGNATION VARCHAR(100) NULL,
    APPROVAL_STATUS VARCHAR(30) NULL,
    CURRENT_MODULE VARCHAR(10) NULL,
    CURRENT_MODULE_NAME VARCHAR(100) NULL,
    CURRENT_PAGE_ID VARCHAR(10) NULL,
    CURRENT_PAGE_NAME VARCHAR(100) NULL,
    AADHAAR_LOOKUP_HASH VARCHAR(64) NULL,
    AADHAAR_LAST_FOUR CHAR(4) NULL,
    PASSWORD_HASH VARCHAR(100) NOT NULL,
    ROLE VARCHAR(50) NOT NULL,
    ACCOUNT_STATUS VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    VERIFICATION_REQUIRED BOOLEAN NOT NULL DEFAULT FALSE,
    LAST_LOGIN_AT TIMESTAMP NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (USER_ID),
    UNIQUE KEY UK_DC_USER_EMPLOYEE (EMPLOYEE_ID),
    UNIQUE KEY UK_DC_USER_CITIZEN (CITIZEN_ID),
    UNIQUE KEY UK_DC_USER_MOBILE (MOBILE_NUMBER),
    UNIQUE KEY UK_DC_USER_EMAIL (EMAIL),
    UNIQUE KEY UK_DC_USER_AADHAAR_HASH (AADHAAR_LOOKUP_HASH),
    CHECK (PROFILE_TYPE IN ('GOVERNMENT_OFFICIAL','CITIZEN')),
    CHECK (ACCOUNT_STATUS IN ('ACTIVE','PENDING_VERIFICATION','DISABLED','LOCKED'))
);

CREATE TABLE IF NOT EXISTS DC_AUTH_SESSION (
    SESSION_ID BIGINT NOT NULL AUTO_INCREMENT,
    USER_ID BIGINT NOT NULL,
    REFRESH_TOKEN_HASH VARCHAR(100) NOT NULL,
    EXPIRES_AT TIMESTAMP NOT NULL,
    REVOKED_AT TIMESTAMP NULL,
    CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (SESSION_ID),
    UNIQUE KEY UK_DC_AUTH_REFRESH_TOKEN (REFRESH_TOKEN_HASH),
    KEY IX_DC_AUTH_SESSION_USER (USER_ID),
    CONSTRAINT FK_DC_AUTH_SESSION_USER FOREIGN KEY (USER_ID)
        REFERENCES DC_USER_ACCOUNT(USER_ID) ON DELETE CASCADE
);

