CREATE TABLE IF NOT EXISTS DC_DISABILITY (
    DISABILITY_ID BIGINT NOT NULL AUTO_INCREMENT,
    APPLICATION_NO VARCHAR(8) NOT NULL,
    PERSON_ID INT NOT NULL,
    DISABILITY_TYPES VARCHAR(1000) NOT NULL,
    OTHER_DISABILITY_DETAILS VARCHAR(1000) DEFAULT NULL,
    PROOF_OF_DISABILITY VARCHAR(100) NOT NULL,
    DISABILITY_VERIFICATION VARCHAR(150) DEFAULT NULL,
    DISABILITY_START_DATE DATE NOT NULL,
    SAME_AS_BIRTH_DATE BOOLEAN NOT NULL DEFAULT FALSE,
    CERTIFICATE_NUMBER VARCHAR(150) DEFAULT NULL,
    ISSUING_AUTHORITY VARCHAR(255) DEFAULT NULL,
    CERTIFICATE_ISSUE_DATE DATE DEFAULT NULL,
    CERTIFICATE_VALIDITY_TYPE VARCHAR(50) DEFAULT NULL,
    CERTIFICATE_EXPIRY_DATE DATE DEFAULT NULL,
    DISABILITY_PERCENTAGE INT DEFAULT NULL,
    CREATED_DATE DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UPDATED_DATE DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (DISABILITY_ID),
    KEY IDX_DC_DISABILITY_APPLICATION_NO (APPLICATION_NO),
    KEY IDX_DC_DISABILITY_PERSON_ID (PERSON_ID),
    CONSTRAINT FK_DC_DISABILITY_APPLICATION FOREIGN KEY (APPLICATION_NO)
        REFERENCES DC_APPLICATION (APPLICATION_NO) ON DELETE CASCADE,
    CONSTRAINT FK_DC_DISABILITY_PERSON FOREIGN KEY (PERSON_ID)
        REFERENCES DC_PERSON (PERSON_ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
